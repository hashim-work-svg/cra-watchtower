// Package drafts generates EU Cyber Resilience Act (CRA) Article 14 notification drafts
// for CSIRTs and the ENISA Single Reporting Platform.
package drafts

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/hashim-work-svg/cra-watchtower/internal/clock"
	"github.com/hashim-work-svg/cra-watchtower/internal/matcher"
)

const LegalDisclaimer = `> [!IMPORTANT]
> **DISCLAIMER: NOT LEGAL ADVICE**
> This draft was generated by CRA Vulnerability Watchtower as a technical compliance aid.
> Article 14 of Regulation (EU) 2024/2847 requires manufacturers to notify the designated
> CSIRT and ENISA. All automated technical data must be reviewed and authorized by
> designated legal, compliance, and cybersecurity authorities prior to official submission.`

// DraftSet bundles the three regulatory notification Markdown documents.
type DraftSet struct {
	EarlyWarning string `json:"early_warning"`
	Notification string `json:"notification"`
	FinalReport  string `json:"final_report"`
}

// GenerateDrafts produces Stage 1, Stage 2, and Stage 3 CRA Markdown notification templates.
func GenerateDrafts(f matcher.Finding, productName, productVersion string, tl clock.Timeline) DraftSet {
	return DraftSet{
		EarlyWarning: generateEarlyWarning(f, productName, productVersion, tl),
		Notification: generateNotification(f, productName, productVersion, tl),
		FinalReport:  generateFinalReport(f, productName, productVersion, tl),
	}
}

func generateEarlyWarning(f matcher.Finding, prodName, prodVer string, tl clock.Timeline) string {
	var sb strings.Builder

	sb.WriteString("# EU Cyber Resilience Act (CRA) - Article 14(1) Early Warning\n\n")
	sb.WriteString(LegalDisclaimer)
	sb.WriteString("\n\n---\n\n")

	sb.WriteString("## 1. Automated Technical Facts (Watchtower Verified)\n\n")
	sb.WriteString(fmt.Sprintf("- **Product Name:** `%s`\n", prodName))
	sb.WriteString(fmt.Sprintf("- **Product Version:** `%s`\n", prodVer))
	sb.WriteString(fmt.Sprintf("- **Affected Component:** `%s` (v`%s`)\n", f.Component.Name, f.Component.Version))
	sb.WriteString(fmt.Sprintf("- **Package URL (PURL):** `%s`\n", f.Component.PURL))
	sb.WriteString(fmt.Sprintf("- **Vulnerability ID:** `%s`\n", f.VulnerabilityID))
	sb.WriteString(fmt.Sprintf("- **CVE ID:** `%s`\n", f.CVEID))
	sb.WriteString(fmt.Sprintf("- **Severity Score:** `%s`\n", f.Severity))
	sb.WriteString(fmt.Sprintf("- **Actively Exploited Candidate (CISA KEV):** `%t`\n", f.IsActivelyExploitedCandidate))
	if f.KEVDetails != nil {
		sb.WriteString(fmt.Sprintf("  - *KEV Date Added:* %s\n", f.KEVDetails.DateAdded))
		sb.WriteString(fmt.Sprintf("  - *KEV Required Action:* %s\n", f.KEVDetails.RequiredAction))
	}
	sb.WriteString(fmt.Sprintf("- **Awareness Timestamp (UTC):** `%s`\n", tl.AwarenessTime.Format(time.RFC3339)))
	sb.WriteString(fmt.Sprintf("- **Statutory 24-Hour Deadline:** `%s` (**Status: %s**)\n\n",
		tl.EarlyWarning.Deadline.Format(time.RFC3339), tl.EarlyWarning.Status))

	sb.WriteString("## 2. Mandatory Human Input Required (Legal & Incident Team)\n\n")
	sb.WriteString("The following operational fields must be completed by human responders prior to filing:\n\n")
	sb.WriteString("- [ ] **[REQUIRED] Recipient Designated CSIRT:** `[Specify national CSIRT e.g. BSI (DE), ANSSI (FR), CSIRT-IE (IE)]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Incident Responder Name & 24/7 Hotline:** `[Full Name, Direct Telephone, Encrypted Email / PGP Key]`\n")
	sb.WriteString("- [ ] **[REQUIRED] In-the-Wild Exploitation Confirmation:** `[Indicate whether active exploitation has been observed in your customer telemetry or internal logs]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Initial Containment / Temporary Mitigations:** `[List any immediate workarounds, firewall/WAF rules, or disablement of vulnerable features]`\n\n")

	sb.WriteString("---\n*Generated by CRA Vulnerability Watchtower on " + tl.Now.Format(time.RFC3339) + "*\n")
	return sb.String()
}

func generateNotification(f matcher.Finding, prodName, prodVer string, tl clock.Timeline) string {
	var sb strings.Builder

	sb.WriteString("# EU Cyber Resilience Act (CRA) - Article 14(2) Vulnerability Notification\n\n")
	sb.WriteString(LegalDisclaimer)
	sb.WriteString("\n\n---\n\n")

	sb.WriteString("## 1. Automated Technical Facts (Watchtower Verified)\n\n")
	sb.WriteString(fmt.Sprintf("- **Product:** `%s` (v`%s`)\n", prodName, prodVer))
	sb.WriteString(fmt.Sprintf("- **Component:** `%s` (v`%s`)\n", f.Component.Name, f.Component.Version))
	sb.WriteString(fmt.Sprintf("- **PURL:** `%s`\n", f.Component.PURL))
	sb.WriteString(fmt.Sprintf("- **Vulnerability ID:** `%s`\n", f.VulnerabilityID))
	sb.WriteString(fmt.Sprintf("- **CVE ID:** `%s`\n", f.CVEID))
	sb.WriteString(fmt.Sprintf("- **Severity:** `%s`\n", f.Severity))
	if f.FixedIn != "" {
		sb.WriteString(fmt.Sprintf("- **Known Fixed Upstream Version:** `%s`\n", f.FixedIn))
	}
	sb.WriteString(fmt.Sprintf("- **Summary:** %s\n", f.Summary))
	sb.WriteString(fmt.Sprintf("- **Statutory 72-Hour Deadline:** `%s` (**Status: %s**)\n\n",
		tl.Notification.Deadline.Format(time.RFC3339), tl.Notification.Status))

	sb.WriteString("## 2. Mandatory Human Input Required (Legal & Incident Team)\n\n")
	sb.WriteString("- [ ] **[REQUIRED] Information Sensitivity Assessment:** `[Specify confidentiality level under CRA Art 14(6): TLP:AMBER / TLP:RED / RESTRICTED]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Technical Root Cause Analysis:** `[Detail the underlying software defect and exploit path within product architecture]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Customer & Market Impact Assessment:** `[Estimate number of deployed units, critical infrastructure exposure, and safety risks]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Patch / Mitigation Release Schedule:** `[Commitment date for security update or firmware release]`\n\n")

	sb.WriteString("---\n*Generated by CRA Vulnerability Watchtower on " + tl.Now.Format(time.RFC3339) + "*\n")
	return sb.String()
}

func generateFinalReport(f matcher.Finding, prodName, prodVer string, tl clock.Timeline) string {
	var sb strings.Builder

	sb.WriteString("# EU Cyber Resilience Act (CRA) - Article 14(4) Final Report\n\n")
	sb.WriteString(LegalDisclaimer)
	sb.WriteString("\n\n---\n\n")

	sb.WriteString("## 1. Automated Technical Facts (Watchtower Verified)\n\n")
	sb.WriteString(fmt.Sprintf("- **Product:** `%s` (v`%s`)\n", prodName, prodVer))
	sb.WriteString(fmt.Sprintf("- **Component:** `%s` (v`%s`)\n", f.Component.Name, f.Component.Version))
	sb.WriteString(fmt.Sprintf("- **Vulnerability:** `%s` (%s)\n", f.VulnerabilityID, f.CVEID))
	if tl.MitigationTime != nil {
		sb.WriteString(fmt.Sprintf("- **Mitigation Availability Timestamp:** `%s`\n", tl.MitigationTime.Format(time.RFC3339)))
		if tl.FinalReport != nil {
			sb.WriteString(fmt.Sprintf("- **Statutory 14-Day Deadline:** `%s` (**Status: %s**)\n\n",
				tl.FinalReport.Deadline.Format(time.RFC3339), tl.FinalReport.Status))
		}
	} else {
		sb.WriteString("- **Mitigation Availability Timestamp:** `Pending (Final report clock triggers upon mitigation availability)`\n\n")
	}

	sb.WriteString("## 2. Mandatory Human Input Required (CISO & Executive Sign-Off)\n\n")
	sb.WriteString("- [ ] **[REQUIRED] Complete Description of Corrective Measures:** `[Provide release notes, CVE fix verification, SHA-256 hash of released firmware/patch]`\n")
	sb.WriteString("- [ ] **[REQUIRED] User Adoption and Deployment Metrics:** `[Percentage of installed base that has successfully applied the update]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Long-Term Architectural & Process Improvements:** `[Changes to SDLC, supply-chain verification, or automated security gates]`\n")
	sb.WriteString("- [ ] **[REQUIRED] Executive & Legal Sign-Off:** `[Printed Name, Title (e.g. CISO, Chief Legal Counsel), Date & Signature]`\n\n")

	sb.WriteString("---\n*Generated by CRA Vulnerability Watchtower on " + tl.Now.Format(time.RFC3339) + "*\n")
	return sb.String()
}

// SaveDrafts writes the three drafts to the designated output directory.
func SaveDrafts(set DraftSet, outputDir, cveID string) error {
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create drafts output directory %q: %w", outputDir, err)
	}

	cleanCVE := strings.ReplaceAll(strings.ToLower(cveID), ":", "_")
	if cleanCVE == "" {
		cleanCVE = "vulnerability"
	}

	f1 := filepath.Join(outputDir, fmt.Sprintf("%s-stage1-early-warning.md", cleanCVE))
	if err := os.WriteFile(f1, []byte(set.EarlyWarning), 0644); err != nil {
		return fmt.Errorf("failed to write stage 1 draft: %w", err)
	}

	f2 := filepath.Join(outputDir, fmt.Sprintf("%s-stage2-notification.md", cleanCVE))
	if err := os.WriteFile(f2, []byte(set.Notification), 0644); err != nil {
		return fmt.Errorf("failed to write stage 2 draft: %w", err)
	}

	f3 := filepath.Join(outputDir, fmt.Sprintf("%s-stage3-final-report.md", cleanCVE))
	if err := os.WriteFile(f3, []byte(set.FinalReport), 0644); err != nil {
		return fmt.Errorf("failed to write stage 3 draft: %w", err)
	}

	return nil
}
